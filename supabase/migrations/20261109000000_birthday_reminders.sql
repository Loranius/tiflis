begin;

-- Telegram birthday reminders: the day before someone's birthday every active
-- portal user with a linked Telegram gets a reminder — except the birthday
-- person themselves. The roster in staff_birthdays has no auth link by design,
-- so we add an optional link to public.users to know whom to leave out.

alter table public.staff_birthdays
  add column if not exists user_id text references public.users(id) on delete set null;

create index if not exists staff_birthdays_user_id_idx
  on public.staff_birthdays (user_id)
  where user_id is not null;

comment on column public.staff_birthdays.user_id is
  'Optional link to the portal account of this person. Used to skip the birthday person when the day-before Telegram reminder is sent.';

-- Best-effort initial linking: only exact (case/space-insensitive) name matches
-- that are unambiguous on both sides. Everything else is linked by hand in the
-- "День народження" editor.
with roster as (
  select id, lower(regexp_replace(trim(full_name), '\s+', ' ', 'g')) as name_key
  from public.staff_birthdays
  where user_id is null
),
accounts as (
  select id, lower(regexp_replace(trim(display_name), '\s+', ' ', 'g')) as name_key
  from public.users
  where display_name is not null and coalesce(fired, false) = false
),
unique_roster as (
  select name_key from roster group by name_key having count(*) = 1
),
unique_accounts as (
  select name_key, min(id) as user_id from accounts group by name_key having count(*) = 1
)
update public.staff_birthdays b
set user_id = a.user_id
from roster r
join unique_roster ur on ur.name_key = r.name_key
join unique_accounts a on a.name_key = r.name_key
where b.id = r.id;

-- One row per (reminder date, recipient): makes the daily job idempotent, so
-- a retried or duplicated cron run never sends the same reminder twice.
create table if not exists public.birthday_reminder_deliveries (
  id bigint generated by default as identity primary key,
  reminder_date date not null,
  user_id text not null references public.users(id) on delete cascade,
  birthday_ids bigint[] not null,
  delivered boolean not null default false,
  created_at timestamptz not null default now(),
  unique (reminder_date, user_id)
);

comment on table public.birthday_reminder_deliveries is
  'Log of day-before birthday Telegram reminders; unique per recipient per day so the cron job is safe to re-run.';

alter table public.birthday_reminder_deliveries enable row level security;
revoke all on table public.birthday_reminder_deliveries from public, anon, authenticated;
revoke all on sequence public.birthday_reminder_deliveries_id_seq from public, anon, authenticated;
grant select, insert, update, delete on table public.birthday_reminder_deliveries to service_role;
grant usage, select on sequence public.birthday_reminder_deliveries_id_seq to service_role;

commit;

-- Daily schedule. pg_cron runs in UTC; 07:00 UTC is 09:00/10:00 in Kyiv
-- depending on DST, a reasonable time for a reminder. The function URL and the
-- shared secret are read from Supabase Vault so no secret lives in git:
--   select vault.create_secret('https://<project-ref>.supabase.co/functions/v1/tiflis-birthday-reminders', 'birthday_reminders_url');
--   select vault.create_secret('<same value as BIRTHDAY_CRON_SECRET>', 'birthday_reminders_secret');
create extension if not exists pg_cron;
create extension if not exists pg_net;

select cron.unschedule(jobid)
from cron.job
where jobname = 'tiflis-birthday-reminders';

select cron.schedule(
  'tiflis-birthday-reminders',
  '0 7 * * *',
  $cron$
  select net.http_post(
    url := (select decrypted_secret from vault.decrypted_secrets where name = 'birthday_reminders_url'),
    headers := jsonb_build_object(
      'Content-Type', 'application/json',
      'x-cron-secret', (select decrypted_secret from vault.decrypted_secrets where name = 'birthday_reminders_secret')
    ),
    body := '{}'::jsonb,
    timeout_milliseconds := 30000
  )
  where exists (select 1 from vault.decrypted_secrets where name = 'birthday_reminders_url');
  $cron$
);
