begin;

-- Bookings the admin attaches to a zone in the daily duty plan (Обов'язки).
-- Кабінки carry one booking per booth (slot 1..5); Камінний зал and Нижній
-- зал №2/№3 carry one booking per hall (slot 0). They travel to the waiter of
-- the zone with the published duties. Kept apart from the hostesses'
-- Резерви module on purpose.
create table if not exists public.ops_zone_bookings (
  id bigint generated by default as identity primary key,
  work_date date not null,
  zone_key text not null check (zone_key in ('zone_booths', 'zone_fireplace_hall', 'zone_lower_hall_2', 'zone_lower_hall_3')),
  slot smallint not null check (slot between 0 and 5),
  booked_time time not null,
  guests integer not null check (guests between 1 and 300),
  guest_name text check (guest_name is null or char_length(guest_name) <= 120),
  has_menu boolean not null default false,
  updated_by text,
  updated_at timestamptz not null default now(),
  unique (work_date, zone_key, slot),
  check ((zone_key = 'zone_booths') = (slot between 1 and 5)),
  check (zone_key = 'zone_booths' or slot = 0)
);

create index if not exists ops_zone_bookings_date_idx on public.ops_zone_bookings (work_date);

comment on table public.ops_zone_bookings is
  'Per-day bookings attached to a duty-plan zone: booths 1..5 (slot) and the fireplace / lower halls (slot 0). Sent to the zone''s waiter with the published duties.';

alter table public.ops_zone_bookings enable row level security;
revoke all on table public.ops_zone_bookings from public, anon, authenticated;
grant select, insert, update, delete on table public.ops_zone_bookings to service_role;
grant usage, select on sequence public.ops_zone_bookings_id_seq to service_role;

-- One row per (shift date, waiter): the breakfast reminder job is safe to re-run.
create table if not exists public.breakfast_reminder_deliveries (
  id bigint generated by default as identity primary key,
  shift_date date not null,
  user_id text not null references public.users(id) on delete cascade,
  delivered boolean not null default false,
  created_at timestamptz not null default now(),
  unique (shift_date, user_id)
);

comment on table public.breakfast_reminder_deliveries is
  'Log of day-before breakfast-shift (СН) Telegram reminders; unique per waiter per shift date.';

alter table public.breakfast_reminder_deliveries enable row level security;
revoke all on table public.breakfast_reminder_deliveries from public, anon, authenticated;
grant select, insert, update, delete on table public.breakfast_reminder_deliveries to service_role;
grant usage, select on sequence public.breakfast_reminder_deliveries_id_seq to service_role;

commit;

-- 09:00 Kyiv all year: pg_cron runs in UTC, so fire at 06:00 and 07:00 UTC and
-- let the function act only when it is 09:00 in Kyiv (summer UTC+3, winter
-- UTC+2). Reuses the birthday job's Vault secrets: same shared secret, and the
-- URL of the sibling function.
create extension if not exists pg_cron;
create extension if not exists pg_net;

select cron.unschedule(jobid)
from cron.job
where jobname = 'tiflis-breakfast-reminders';

select cron.schedule(
  'tiflis-breakfast-reminders',
  '0 6,7 * * *',
  $cron$
  select net.http_post(
    url := replace(
      (select decrypted_secret from vault.decrypted_secrets where name = 'birthday_reminders_url'),
      'tiflis-birthday-reminders',
      'tiflis-breakfast-reminders'
    ),
    headers := jsonb_build_object(
      'Content-Type', 'application/json',
      'x-cron-secret', (select decrypted_secret from vault.decrypted_secrets where name = 'birthday_reminders_secret')
    ),
    body := '{}'::jsonb,
    timeout_milliseconds := 30000
  )
  where exists (select 1 from vault.decrypted_secrets where name = 'birthday_reminders_url');
  $cron$
);
