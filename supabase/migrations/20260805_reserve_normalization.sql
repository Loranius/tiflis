insert into public.reserve_tables (
  hall_id, label, capacity, kind, position_x, position_y, sort_order
)
select h.id, s.label, s.capacity, s.kind, s.x, s.y, s.sort_order
from table_seed s
join public.reserve_halls h on h.name = s.hall_name
on conflict (hall_id, label) do update
set capacity = excluded.capacity,
    kind = excluded.kind,
    position_x = excluded.position_x,
    position_y = excluded.position_y,
    sort_order = excluded.sort_order,
    active = true;

with source as (
  select s.value::jsonb as bookings
  from public.settings s
  where s.key = 'tiflis_reserve_bookings'
), expanded as (
  select
    split_part(bucket.key, '::', 1) as hall_name,
    split_part(bucket.key, '::', 2) as table_label,
    booking.value as booking
  from source
  cross join lateral jsonb_each(source.bookings) as bucket(key, value)
  cross join lateral jsonb_array_elements(bucket.value) as booking(value)
), normalized as (
  select
    h.id as hall_id,
    t.id as table_id,
    (booking->>'date')::date as reserved_date,
    (booking->>'time')::time as reserved_time,
    greatest(1, least(300, coalesce(nullif(booking->>'guests','')::integer, 1)))::smallint as guests,
    left(coalesce(nullif(trim(booking->>'name'), ''), 'Без імені'), 180) as guest_name,
    nullif(left(trim(coalesce(booking->>'phone','')), 80), '') as phone,
    nullif(left(trim(coalesce(booking->>'menu','')), 1000), '') as menu_note,
    case when booking->>'status' in ('booked','occupied','completed','cancelled','no_show')
      then booking->>'status' else 'booked' end as status,
    case when jsonb_typeof(booking->'mergedWith') = 'array'
      then array(select jsonb_array_elements_text(booking->'mergedWith'))
      else array[]::text[] end as merged_tables,
    nullif(left(trim(coalesce(booking->>'createdBy','')), 120), '') as created_by,
    case
      when coalesce(booking->>'createdAt','') <> '' then (booking->>'createdAt')::timestamptz
      else now()
    end as created_at
  from expanded e
  join public.reserve_halls h on h.name = e.hall_name
  join public.reserve_tables t on t.hall_id = h.id and t.label = e.table_label
  where coalesce(booking->>'date','') ~ '^\d{4}-\d{2}-\d{2}$'
    and coalesce(booking->>'time','') ~ '^\d{2}:\d{2}$'
)
insert into public.reservations (
  hall_id, table_id, reserved_date, reserved_time, guests, guest_name,
  phone, menu_note, status, merged_tables, created_by, created_at
)
select
  hall_id, table_id, reserved_date, reserved_time, guests, guest_name,
  phone, menu_note, status, merged_tables, created_by, created_at
from normalized
on conflict (hall_id, table_id, reserved_date, reserved_time, guest_name) do nothing;

