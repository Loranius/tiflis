begin;

create table if not exists public.reserve_halls (
  id bigint generated by default as identity primary key,
  name text not null unique,
  sort_order integer not null default 0,
  note text,
  active boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.reserve_tables (
  id bigint generated by default as identity primary key,
  hall_id bigint not null references public.reserve_halls(id) on delete cascade,
  label text not null,
  capacity smallint not null default 4 check (capacity between 1 and 100),
  kind text not null default 'small',
  position_x numeric(8,3),
  position_y numeric(8,3),
  sort_order integer not null default 0,
  active boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (hall_id, label)
);

create table if not exists public.reservations (
  id bigint generated by default as identity primary key,
  hall_id bigint not null references public.reserve_halls(id) on delete restrict,
  table_id bigint not null references public.reserve_tables(id) on delete restrict,
  reserved_date date not null,
  reserved_time time without time zone not null,
  duration_minutes smallint not null default 120 check (duration_minutes between 15 and 720),
  guests smallint not null default 2 check (guests between 1 and 300),
  guest_name text not null,
  phone text,
  menu_note text,
  note text,
  status text not null default 'booked' check (status in ('booked','occupied','completed','cancelled','no_show')),
  merged_tables text[] not null default array[]::text[],
  created_by text,
  updated_by text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create index if not exists reservations_date_hall_idx
  on public.reservations (reserved_date, hall_id, reserved_time);
create index if not exists reservations_table_slot_idx
  on public.reservations (table_id, reserved_date, reserved_time);
create index if not exists reservations_active_status_idx
  on public.reservations (reserved_date, status)
  where status in ('booked','occupied');
create unique index if not exists reservations_legacy_identity_unique
  on public.reservations (hall_id, table_id, reserved_date, reserved_time, guest_name);

